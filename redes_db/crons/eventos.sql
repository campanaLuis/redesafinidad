CREATE TABLE redes_afinidad.eventos (
  id int GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  nombre text,
  categoria text,
  fecha date DEFAULT CURRENT_DATE,
  horadeinicio timestamp DEFAULT now(),
  horadefin timestamp DEFAULT now(),
  ubicacion text,
  capacidadmaxima int
);
